package main

import "fmt"

//3. Буферизованный vs небуферизованный канал
//Сравните поведение:
//Небуферизованного канала (make(chan int)).
//Буферизованного (make(chan int, 3)).
//Отправьте 3 значения без чтения и посмотрите, где происходит блокировка.
//Цель: понять разницу между буферизованными и небуферизованными каналами.

func main() {
	fmt.Println("=== Небуферизованный канал ===")
	// Создаем небуферизованный канал
	unbufChan := make(chan int)

	go func() {
		// Отправляем значение 1 в канал.
		// Поскольку канал небуферизованный, эта операция блокируется до тех пор,
		// пока другая горутина не прочитает из канала.
		unbufChan <- 1
		fmt.Println("Отправлено 1 в небуферизованный канал")

		// Вторая отправка: она заблокируется, пока первое значение не будет прочитано.
		unbufChan <- 2
		fmt.Println("Отправлено 2 в небуферизованный канал")

		// Закрываем канал после отправки всех значений.
		close(unbufChan)
	}()

	// Читаем значения из канала в главной горутине.
	// Первое чтение: разблокирует горутину-отправитель после отправки 1.
	fmt.Println("Прочитано из небуферизованного канала:", <-unbufChan)
	// Второе чтение: разблокирует горутину-отправитель после отправки 2.
	fmt.Println("Прочитано из небуферизованного канала:", <-unbufChan)

	fmt.Println("=== Буферизованный канал ===")

	bufChan := make(chan int, 3)

	// Отправляем три значения в буферизованный канал.
	// Поскольку буфер рассчитан на три значения, эти отправки не блокируются.
	bufChan <- 1
	fmt.Println("Отправлено 1 в буферизованный канал")
	bufChan <- 2
	fmt.Println("Отправлено 2 в буферизованный канал")
	bufChan <- 3
	fmt.Println("Отправлено 3 в буферизованный канал")

	// Если бы мы попытались отправить четвертое значение без чтения, это заблокировало бы горутину, так как буфер полон.
	// Но мы не отправляем четвертое значение.

	// Читаем три значения из буферизованного канала.
	// Эти чтения не блокируются, потому что в буфере есть данные.
	fmt.Println("Прочитано из буферизованного канала:", <-bufChan)
	fmt.Println("Прочитано из буферизованного канала:", <-bufChan)
	fmt.Println("Прочитано из буферизованного канала:", <-bufChan)
}

package main

import "fmt"

//4. Закрытие каналов
//Создайте канал, отправьте в него данные, закройте его и попробуйте:
//Прочитать данные после закрытия.
//Отправить данные в закрытый канал (паника!).
//Цель: изучить поведение закрытых каналов.

func main() {
	ch := make(chan int, 3)

	// Отправляем три значения в канал
	ch <- 1
	ch <- 2
	ch <- 3

	// Закрываем канал - больше нельзя отправлять данные
	close(ch)

	// Читаем данные после закрытия - это безопасно
	// Первое чтение: вернет 1 и true
	value, ok := <-ch
	fmt.Println("Прочитано: ", value, ", Канал открыт: ", ok)

	// Второе чтение: вернет 2 и true
	value, ok = <-ch
	fmt.Println("Прочитано: ", value, ", Канал открыт: ", ok)

	// Третье чтение: вернет 3 и true
	value, ok = <-ch
	fmt.Println("Прочитано: ", value, ", Канал открыт: ", ok)

	// Четвертое чтение: канал пуст и закрыт
	// Вернет 0 (нулевое значение для int) и false
	value, ok = <-ch
	fmt.Println("Прочитано: ", value, ", Канал открыт: ", ok)

	// Попытка отправить данные в закрытый канал вызовет панику

	// ch <- 4 // panic: send on closed channel
}

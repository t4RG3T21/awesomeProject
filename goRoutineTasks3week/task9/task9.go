package main

import (
	"fmt"
	"time"
)

// worker - горутина, которая выполняет работу до получения сигнала остановки
// Параметры:
// id - идентификатор рабочего
// stopChan - канал только для чтения, используемый для получения сигнала остановки

func worker(id int, stopChan <-chan bool) {
	fmt.Printf("Воркер %d начал работу\n", id)

	// бесконечный цикл, который будет прерван сигналом остановки
	for {
		select {
		case <-stopChan:
			// получен сигнал остановки
			fmt.Printf("Воркер %d получил сигнал остановки. Завершаю работу.\n", id)
			return // выходим из функции, тем самым завершая работы
		default:
			// если сигнала остановки нет, продолжаем работу
			fmt.Printf("Воркер %d выполняет работу...\n", id)
			time.Sleep(500 * time.Millisecond) // имитация работы
		}
	}
}

func main() {
	// создаем канал для сигнала остановки
	stopChan := make(chan bool)

	// запускаем несколько горутин
	for i := 1; i <= 3; i++ {
		go worker(i, stopChan)
	}

	// даём горутинам поработать 3 секунды
	fmt.Println("Горутины работают...")
	time.Sleep(3 * time.Second)

	// отправляем сигнал остановки всем горутинам
	fmt.Println("Отправляем сигнал остановки...")
	close(stopChan) // закрытие канала - специальный сигнал для всех получателей

	// даём время горутинам корректно завершиться

	time.Sleep(1 * time.Second)
	fmt.Println("Все горутины остановлены")
}
